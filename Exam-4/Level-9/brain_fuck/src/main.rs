    #[cfg(test)]
    mod tests {
        use std::process::Command;

        const MANIFEST_PATH: &str = "../brain_fuck/Cargo.toml";

        fn run(s: &str) -> String {
            let output = Command::new("cargo")
                .arg("run")
                .arg("--manifest-path")
                .arg(MANIFEST_PATH)
                .arg(s)
                .output()
                .expect("Failed to execute command");

            String::from_utf8(output.stdout).unwrap()
        }

        #[test]
        fn nothing_passed() {
            assert!(run("").is_empty());
        }

        #[test]
        fn single_chars() {
            assert_eq!(
                "a",
                run("++++++++++[>+>+++>+++++++>++++++++++<<<<-]>>>>---.")
            );
            assert_eq!(
                "S",
                run("++++++++++[>+>+++>+++++++>++++++++++<<<<-]>>>+++++++++++++.")
            );
            assert_eq!(
                "7",
                run("++++++++++[>+>+++>+++++++>++++++++++<<<<-]>>>---------------.")
            );
        }

        #[test]
        fn phrases() {
            assert_eq!(
                "Wow",
                run(
                    "++++++++++[>+>+++>+++++++>++++++++++<<<<-]>>>>-------------.++++++++++++++++++++++++.++++++++."
                )
            );
            assert_eq!(
                "Good job!",
                run(
                    "++++++++++[>+>+++>+++++++>++++++++++<<<<-]>>>+.>+++++++++++..-----------.<<++.>>++++++.+++++.-------------.<<+."
                )
            );
        }

        #[test]
        fn with_characters_in_middle() {
            assert_eq!(
                "keep going",
                run(
                    "++++++++++[>+>ke+++>+++++++>++++++++++<<<<-]>>>>+++++++e.------p..+++++++++++.<<++.>g>---------.+o+++++++.------i.+++++.-n------.g"
                )
            );
        }

        #[test]
        fn big_test() {
            assert_eq!(
                "3, 2, 1... Happy New Year",
                run(
                    "++++++++++[>+>+++>+++++++>++++++++++<<<<-]>>>-------------------.-------.<++.>++++++.------.<.>+++++.---...<.>++++++++++++++++++++++++++.>---.+++++++++++++++..+++++++++.<<.>++++++.>--------------------.++++++++++++++++++.<<.>+++++++++++.++++++++++++.----.>-----."
                )
            );
            assert_eq!(
                "To be or not be, that is the question!",
                run(
                    "++++++++++[>+>+++>+++++++>++++++++++<<<<-]>>>++++++++++++++.>+++++++++++.<<++.>>-------------.+++.<<.>>++++++++++.+++.<<.>>----.+.+++++.<<.>++++++++++++++.+++.<++++++++++++.------------.>>.<+++.-------.>.<<.>++++++++.>-.<<.>>+.<-.---.<.>>---.++++.<.>--.+.<++++.>-----.-.<<+."
                )
            );
        }
    }