use std::env::args;
fn main() {
    let code: Vec<char> = args().nth(1).unwrap_or_default().chars().collect();
    let mut tape = [0u8; 2048];
    let mut ptr = 0usize;
    let mut pc = 0usize;
    while pc < code.len() {
        match code[pc] {
            '>' => ptr += 1,
            '<' => ptr -= 1,
            '+' => tape[ptr] = tape[ptr].wrapping_add(1),
            '-' => tape[ptr] = tape[ptr].wrapping_sub(1),
            '.' => print!("{}", tape[ptr] as char),
            '[' if tape[ptr] == 0 => {
                let mut depth = 1;
                while depth > 0 {
                    pc += 1;
                    match code[pc] {
                        '[' => depth += 1,
                        ']' => depth -= 1,
                        _ => {}
                    }
                }
            }
            ']' if tape[ptr] != 0 => {
                let mut depth = 1;
                while depth > 0 {
                    pc -= 1;
                    match code[pc] {
                        ']' => depth += 1,
                        '[' => depth -= 1,
                        _ => {}
                    }
                }
            }
            _ => {}
        }
        pc += 1;
    }
}






















